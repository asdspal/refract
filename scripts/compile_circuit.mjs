#!/usr/bin/env node
/**
 * Compile the depth-20 zkAPI note-spend circuit and generate all artifacts:
 *   - public/circuits/refract_note_spend.wasm
 *   - public/circuits/refract_note_spend_final.zkey
 *   - programs/refract_vault/src/verifying_key.rs
 *
 * Uses the deterministic Hermez Powers-of-Tau (pot14) for Phase 1 and a fixed
 * deterministic Phase-2 contribution. NOTE: a fixed contribution is NOT a
 * production-grade ceremony; it is reproducible test/demo material only.
 */
import { execFileSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const buildDir = join(root, "build/circuits");
const circuit = join(root, "circuits/refract_note_spend.circom");
const ptau = join(root, "circuits/pot14_final.ptau");
const PTAU_URL =
  "https://hermez.s3-eu-west-1.amazonaws.com/powersOfTau28_hez_final_14.ptau";

const circomBin =
  process.env.CIRCOM_BIN && existsSync(process.env.CIRCOM_BIN)
    ? process.env.CIRCOM_BIN
    : join(homedir(), ".cargo/bin/circom");
const snarkjsBin = join(root, "node_modules/.bin/snarkjs");

function run(bin, args) {
  console.log(`$ ${bin.split("/").pop()} ${args.join(" ")}`);
  execFileSync(bin, args, { stdio: "inherit", cwd: root });
}

async function ensurePtau() {
  if (existsSync(ptau) && statSync(ptau).size > 1_000_000) return;
  try {
    console.log(`Downloading pot14 (~40MB) -> ${ptau}`);
    const res = await fetch(PTAU_URL);
    if (!res.ok) throw new Error(`PTAU download failed: HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 1_000_000) throw new Error("PTAU download too small");
    writeFileSync(ptau, buf);
    return;
  } catch (err) {
    console.warn(
      `PTAU download unavailable (${err.message}); generating pot14 locally with snarkjs.`,
    );
  }

  // Hermez CDN is unreachable from this environment. Generate a reproducible
  // Phase-1 locally. This is a deterministic dev/demo ceremony, not production.
  const p0 = join(buildDir, "pot14_0000.ptau");
  const p1 = join(buildDir, "pot14_0001.ptau");
  run(snarkjsBin, ["powersoftau", "new", "bn128", "14", p0]);
  run(snarkjsBin, [
    "powersoftau",
    "contribute",
    p0,
    p1,
    "--name=refract-phase1",
    "-e=refract deterministic phase1 contribution v1",
  ]);
  run(snarkjsBin, ["powersoftau", "prepare", "phase2", p1, ptau]);
  for (const tmp of [p0, p1]) {
    try {
      unlinkSync(tmp);
    } catch {
      // ignore
    }
  }
}

function be32(value) {
  const n = BigInt(value);
  const hex = n.toString(16).padStart(64, "0");
  if (hex.length > 64) throw new Error(`Field element exceeds 32 bytes: ${value}`);
  return Array.from(Buffer.from(hex, "hex"));
}

// snarkjs stores G2 as [[x_c0, x_c1], [y_c0, y_c1]];
// groth16-solana / alt_bn128 expects [x_c1, x_c0, y_c1, y_c0].
function g2(point) {
  return [
    ...be32(point[0][1]),
    ...be32(point[0][0]),
    ...be32(point[1][1]),
    ...be32(point[1][0]),
  ];
}

function g1(point) {
  return [...be32(point[0]), ...be32(point[1])];
}

function arrayLiteral(bytes, indent) {
  const pad = " ".repeat(indent);
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push(pad + bytes.slice(i, i + 16).join(", ") + ",");
  }
  return `[\n${lines.join("\n")}\n${" ".repeat(indent - 4)}]`;
}

function generateVerifyingKey(vkPath, outPath) {
  const vk = JSON.parse(readFileSync(vkPath, "utf8"));
  const ic = vk.IC.map(g1);
  const rust = `// AUTO-GENERATED by scripts/compile_circuit.mjs. Do not edit by hand.
// Circuit: circuits/refract_note_spend.circom (depth-20 Poseidon, ${vk.nPublic} public inputs)
use groth16_solana::groth16::Groth16Verifyingkey;

pub const NR_PUBLIC_INPUTS: usize = ${vk.nPublic};

pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: NR_PUBLIC_INPUTS,
    vk_alpha_g1: ${arrayLiteral(g1(vk.vk_alpha_1), 8)},
    vk_beta_g2: ${arrayLiteral(g2(vk.vk_beta_2), 8)},
    vk_gamme_g2: ${arrayLiteral(g2(vk.vk_gamma_2), 8)},
    vk_delta_g2: ${arrayLiteral(g2(vk.vk_delta_2), 8)},
    vk_ic: &[
${ic.map((p) => "        " + arrayLiteral(p, 12)).join(",\n")}
    ],
};
`;
  writeFileSync(outPath, rust);
  console.log(`Wrote ${outPath} (${ic.length} IC points)`);
}

async function main() {
  if (!existsSync(circomBin)) {
    throw new Error(`circom not found at ${circomBin}. Set CIRCOM_BIN or install circom.`);
  }
  mkdirSync(buildDir, { recursive: true });
  mkdirSync(join(root, "public/circuits"), { recursive: true });

  await ensurePtau();

  run(circomBin, [
    circuit,
    "--r1cs",
    "--wasm",
    "--sym",
    "-l",
    "node_modules",
    "-o",
    buildDir,
  ]);

  const r1cs = join(buildDir, "refract_note_spend.r1cs");
  const zkey0 = join(buildDir, "refract_note_spend_0000.zkey");
  const zkeyFinal = join(buildDir, "refract_note_spend_final.zkey");
  const vkJson = join(buildDir, "verification_key.json");
  const wasm = join(buildDir, "refract_note_spend_js/refract_note_spend.wasm");

  run(snarkjsBin, ["groth16", "setup", r1cs, ptau, zkey0]);
  run(snarkjsBin, [
    "zkey",
    "contribute",
    zkey0,
    zkeyFinal,
    "--name=refract-phase2",
    "-e=refract deterministic phase2 contribution v1",
  ]);
  run(snarkjsBin, ["zkey", "export", "verificationkey", zkeyFinal, vkJson]);

  copyFileSync(wasm, join(root, "public/circuits/refract_note_spend.wasm"));
  copyFileSync(zkeyFinal, join(root, "public/circuits/refract_note_spend_final.zkey"));
  generateVerifyingKey(vkJson, join(root, "programs/refract_vault/src/verifying_key.rs"));

  console.log("\nCircuit artifacts ready:");
  console.log("  public/circuits/refract_note_spend.wasm");
  console.log("  public/circuits/refract_note_spend_final.zkey");
  console.log("  programs/refract_vault/src/verifying_key.rs");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
